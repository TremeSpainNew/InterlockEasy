const assert = require('node:assert/strict'), fs = require('node:fs'), vm = require('node:vm');
const context = vm.createContext({});
vm.runInContext(fs.readFileSync('data/resources.js','utf8') + '\nthis.resources = Resources;', context);
const {usage, free} = context.resources;
const config = () => ({inputs:Array.from({length:64},()=>({enabled:false})),outputs:Array.from({length:64},()=>({enabled:false})),signals:[],cvs:[],axleCounters:[],turnouts:[]});
const d = config();
d.inputs[0].enabled = true;
d.outputs[0].enabled = true;
d.cvs = [{enabled:true,id:'CV1',input:2}];
d.axleCounters = [{enabled:true,id:'CE1',inputA:3,inputB:4}];
d.turnouts = [{enabled:true,id:'T1',outputNormal:2,outputReverse:3,inputNormal:5,inputReverse:6}];
d.signals = [{enabled:true,numeric:true,name:'A1',lights:[{relay:64}]}];
assert.deepEqual(Array.from(free(d,'inputs',2)), [7,8]);
assert.deepEqual(Array.from(free(d,'outputs',2)), [4,5]);
usage(d);
d.beacons = [{enabled:true,name:'B1',relays:[5,6]}];
assert.deepEqual(Array.from(free(d,'outputs',2)), [4,7]);
usage(d);
d.beacons.push({enabled:true,name:'B2',relays:[6]});
assert.throws(()=>usage(d), /RO6.*baliza B1.*baliza B2/);
d.beacons.pop();
d.signals.push({enabled:true,name:'S1',lights:[{relay:3}]});
assert.throws(()=>usage(d), /RO3.*señal S1.*desvío T1/);
d.signals[1].enabled=false;
usage(d);
d.signals[1].lights[0].relay=4;
assert.deepEqual(Array.from(free(d,'outputs')), [7]); // Drafts also avoid each other.
d.cvs.push({enabled:true,id:'CV2',input:6});
assert.throws(()=>usage(d), /DI6.*CV CV2.*desvío T1/);
d.cvs.pop();
d.outputs.forEach(x=>x.enabled=true);
assert.throws(()=>free(d,'outputs'), /No hay suficientes/);
const empty=config();empty.inputs=[];
assert.throws(()=>free(empty,'inputs'), /No hay suficientes/);
const high=config();high.signals=[{enabled:true,name:'S64',lights:[{relay:64},{relay:64}]}];
assert.throws(()=>usage(high), /RO64/);
console.log('OK: shared ownership, cross-page conflicts, drafts, channel 64 and exhaustion');
